use anyhow::{bail, Context, Result};
use clap::{Args, Subcommand};
use serde::Serialize;
use std::path::PathBuf;
use uuid::Uuid;

use strata_core::a2a::IpcEvent;
use strata_core::blackboard::{TaskArtifact, TaskFilter, TaskPayload, TaskRecord, TaskStatus};
use strata_memory::{endpoint_for_workspace, IpcClient, StigmergyCoordinator};

use crate::agent_env::{is_json_mode, resolve_agent_id, resolve_task_id};

#[derive(Args, Debug)]
pub struct TaskArgs {
    #[command(subcommand)]
    pub action: TaskAction,
}

#[derive(Subcommand, Debug)]
pub enum TaskAction {
    /// List tasks on the multi-agent blackboard
    List {
        #[arg(long, help = "Filter by plan ID")]
        plan: Option<String>,

        #[arg(long, help = "Filter by status: pending, claimed, running, blocked, completed, failed")]
        status: Option<String>,

        #[arg(long, help = "Filter by assigned agent ID")]
        agent: Option<String>,

        #[arg(long, default_value_t = 50, help = "Max tasks to return")]
        limit: usize,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Create a new task on the blackboard
    Create {
        #[arg(help = "Title or description of the task")]
        title: String,

        #[arg(long, help = "Optional custom task ID")]
        id: Option<String>,

        #[arg(long, help = "Plan ID this task belongs to")]
        plan: Option<String>,

        #[arg(long, help = "Detailed task description")]
        description: Option<String>,

        #[arg(long, help = "Shell command to execute for this task")]
        cmd: Option<String>,

        #[arg(long, help = "Agent prompt for this task")]
        prompt: Option<String>,

        #[arg(long, help = "Explicit task payload type (shell_command, agent_prompt, manual_verification, descriptive)")]
        r#type: Option<String>,

        #[arg(long, help = "Comma-separated list of prerequisite task IDs")]
        dependencies: Option<String>,

        #[arg(long, help = "Comma-separated list of required resource locks (e.g. 'file:src/lib.rs')")]
        resources: Option<String>,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Atomically claim a task and lock its required resources (Work-Stealing)
    Claim {
        #[arg(help = "Specific task ID to claim")]
        task: Option<String>,

        #[arg(long, help = "Work-stealing mode: claim the next ready, unblocked task in the plan")]
        next: bool,

        #[arg(long, help = "Agent ID claiming the task (defaults to STRATA_AGENT_ID or host-pid)")]
        agent: Option<String>,

        #[arg(long, default_value_t = 180, help = "Lease TTL in seconds for locked resources (default: 180s)")]
        ttl: i64,

        #[arg(long, help = "Comma-separated list of supported task payload types (e.g. 'shell_command')")]
        types: Option<String>,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Report ongoing progress or heartbeat for a claimed task
    Progress {
        #[arg(help = "Task ID (defaults to STRATA_TASK_ID)")]
        task: Option<String>,

        #[arg(long, help = "Progress update or status message")]
        message: String,

        #[arg(long, help = "Agent ID (defaults to STRATA_AGENT_ID)")]
        agent: Option<String>,

        #[arg(long, help = "Expected claim generation (fencing token)")]
        generation: Option<i64>,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Mark a task as successfully completed, release locks, and unblock downstream tasks
    Complete {
        #[arg(help = "Task ID (defaults to STRATA_TASK_ID)")]
        task: Option<String>,

        #[arg(long, help = "Executive summary of the delivered work")]
        summary: Option<String>,

        #[arg(long, help = "Path to file artifact generated by this task to attach")]
        artifact: Option<PathBuf>,

        #[arg(long, help = "Direct string payload for the artifact")]
        artifact_content: Option<String>,

        #[arg(long, help = "Agent ID (defaults to STRATA_AGENT_ID)")]
        agent: Option<String>,

        #[arg(long, help = "Expected claim generation (fencing token)")]
        generation: Option<i64>,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Mark a task as failed and release its resource locks
    Fail {
        #[arg(help = "Task ID (defaults to STRATA_TASK_ID)")]
        task: Option<String>,

        #[arg(long, help = "Error message or failure reason")]
        error: String,

        #[arg(long, help = "Agent ID (defaults to STRATA_AGENT_ID)")]
        agent: Option<String>,

        #[arg(long, help = "Expected claim generation (fencing token)")]
        generation: Option<i64>,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Inspect a task in detail, including upstream dependencies and attached artifacts
    Inspect {
        #[arg(help = "Task ID to inspect")]
        task: String,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Return orphaned tasks (claimed/running, no progress heartbeat) to the pool
    Reclaim {
        #[arg(long, default_value_t = 600, help = "Seconds without progress before a task is considered orphaned")]
        stale_after: i64,

        #[arg(long, help = "Output as raw JSON")]
        json: bool,
    },

    /// Run autonomous blackboard task worker daemon (work-stealing, execution, heartbeats)
    Worker(crate::commands::worker::WorkerArgs),
}

#[derive(Serialize)]
struct ClaimResponse {
    status: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    task: Option<TaskRecord>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    upstream_artifacts: Vec<TaskArtifact>,
    #[serde(skip_serializing_if = "Option::is_none")]
    message: Option<String>,
}

pub async fn run_task(args: TaskArgs, coordinator: StigmergyCoordinator) -> Result<()> {
    match args.action {
        TaskAction::List {
            plan,
            status,
            agent,
            limit,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let parsed_status = match status {
                Some(s) => Some(s.parse::<TaskStatus>().map_err(|e| anyhow::anyhow!(e))?),
                None => None,
            };

            let filter = TaskFilter {
                plan_id: plan,
                status: parsed_status,
                assigned_agent: agent,
                limit: Some(limit),
            };

            let tasks = coordinator.list_tasks(&filter)?;

            if json_mode {
                println!("{}", serde_json::to_string_pretty(&tasks)?);
            } else {
                println!("\n📋 [Strata Multi-Agent Blackboard Tasks]");
                println!("═════════════════════════════════════════════════════════════════════════════");
                if tasks.is_empty() {
                    println!("  (No tasks found matching filter)");
                } else {
                    for t in &tasks {
                        let agent_str = t.assigned_agent.as_deref().unwrap_or("-");
                        let deps = if t.dependencies.is_empty() {
                            "-".to_string()
                        } else {
                            t.dependencies.join(",")
                        };
                        println!(
                            "  • [{:<9}] {:<18} agent={:<12} deps=[{}] title='{}'",
                            t.status.as_str(),
                            t.task_id,
                            agent_str,
                            deps,
                            t.title
                        );
                    }
                }
                println!();
            }
        }

        TaskAction::Create {
            title,
            id,
            plan,
            description,
            cmd,
            prompt,
            r#type,
            dependencies,
            resources,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let task_id = id.unwrap_or_else(|| format!("task-{}", &Uuid::new_v4().simple().to_string()[..12]));

            let deps: Vec<String> = dependencies
                .map(|d| d.split(',').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()).collect())
                .unwrap_or_default();

            let res: Vec<String> = resources
                .map(|r| r.split(',').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()).collect())
                .unwrap_or_default();

            let status = if deps.is_empty() {
                TaskStatus::Pending
            } else {
                TaskStatus::Blocked
            };

            let mut task = TaskRecord::new(&task_id, &title)
                .with_status(status)
                .with_dependencies(deps)
                .with_required_resources(res);

            if let Some(p) = plan {
                task = task.with_plan_id(p);
            }
            if let Some(desc) = &description {
                task = task.with_description(desc);
            }

            let payload = if let Some(command) = cmd {
                Some(TaskPayload::ShellCommand {
                    command,
                    cwd: None,
                    timeout_secs: None,
                })
            } else if let Some(p) = prompt {
                Some(TaskPayload::AgentPrompt {
                    prompt: p,
                    context_files: vec![],
                    expected_artifacts: vec![],
                })
            } else if let Some(t) = r#type.as_deref() {
                match t.to_lowercase().as_str() {
                    "shell_command" => Some(TaskPayload::ShellCommand {
                        command: description.clone().unwrap_or_default(),
                        cwd: None,
                        timeout_secs: None,
                    }),
                    "agent_prompt" => Some(TaskPayload::AgentPrompt {
                        prompt: description.clone().unwrap_or_default(),
                        context_files: vec![],
                        expected_artifacts: vec![],
                    }),
                    "manual_verification" => Some(TaskPayload::ManualVerification {
                        instructions: description.clone().unwrap_or_default(),
                        checklist: vec![],
                    }),
                    "descriptive" => Some(TaskPayload::Descriptive {
                        details: description.clone(),
                    }),
                    other => bail!("Unknown task type: '{other}'. Expected one of: shell_command, agent_prompt, manual_verification, descriptive"),
                }
            } else {
                None
            };

            if let Some(pay) = payload {
                task = task.with_payload(pay);
            }

            coordinator.create_task(&task)?;

            if json_mode {
                println!("{}", serde_json::to_string_pretty(&task)?);
            } else {
                println!("✓ Task '{}' created with status '{}'.", task.task_id, task.status);
            }
        }

        TaskAction::Claim {
            task,
            next,
            agent,
            ttl,
            types,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let agent_id = resolve_agent_id(agent.as_deref());
            let target_task_id = if next {
                None
            } else {
                resolve_task_id(task.as_deref())
            };

            let supported_types: Option<Vec<&str>> = types.as_ref().map(|s| {
                s.split(',').map(|t| t.trim()).filter(|t| !t.is_empty()).collect()
            });

            let claimed_opt = coordinator.claim_task_atomic_typed(
                target_task_id.as_deref(),
                &agent_id,
                ttl,
                supported_types.as_deref(),
            )?;

            match claimed_opt {
                Some(claimed) => {
                    // Broadcast IPC notification for state change & leases
                    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
                    let (endpoint, _) = endpoint_for_workspace(&cwd);
                    if let Ok(ipc) = IpcClient::connect(&endpoint).await {
                        let _ = ipc
                            .publish(IpcEvent::TaskStateChanged {
                                task_id: claimed.task_id.clone(),
                                plan_id: claimed.plan_id.clone(),
                                old_status: TaskStatus::Pending,
                                new_status: TaskStatus::Claimed,
                                agent_id: Some(agent_id.clone()),
                                timestamp_us: chrono::Utc::now().timestamp_micros(),
                            })
                            .await;
                    }

                    // Fetch upstream artifacts from prerequisite tasks for instant agent context handoff
                    let mut upstream_artifacts = Vec::new();
                    for dep in &claimed.dependencies {
                        if let Ok(arts) = coordinator.get_task_artifacts(dep) {
                            upstream_artifacts.extend(arts);
                        }
                    }

                    if json_mode {
                        let resp = ClaimResponse {
                            status: "claimed",
                            task: Some(claimed),
                            upstream_artifacts,
                            message: None,
                        };
                        println!("{}", serde_json::to_string_pretty(&resp)?);
                    } else {
                        println!("\n🎯 [TASK CLAIMED SUCCESSFULLY]");
                        println!("═════════════════════════════════════════════════════════════");
                        println!("Task ID:     \x1b[1;36m{}\x1b[0m", claimed.task_id);
                        println!("Title:       {}", claimed.title);
                        println!("Agent:       \x1b[1;32m{}\x1b[0m", agent_id);
                        println!("Fencing Gen: \x1b[1;33m{}\x1b[0m", claimed.claim_generation);
                        println!("Plan:        {}", claimed.plan_id.as_deref().unwrap_or("-"));
                        println!(
                            "Locked Res:  {}",
                            if claimed.required_resources.is_empty() {
                                "none".to_string()
                            } else {
                                claimed.required_resources.join(", ")
                            }
                        );
                        if !upstream_artifacts.is_empty() {
                            println!("\n📦 Attached Upstream Artifacts ({}):", upstream_artifacts.len());
                            for a in &upstream_artifacts {
                                println!("  • [{}] from task {}: {}", a.kind, a.task_id, a.payload);
                            }
                        }
                        println!("\n💡 Tip: When done, run: \x1b[1mstrata task complete {} --summary \"...\"\x1b[0m\n", claimed.task_id);
                    }
                }
                None => {
                    if json_mode {
                        let resp = ClaimResponse {
                            status: "none_available",
                            task: None,
                            upstream_artifacts: vec![],
                            message: Some("No eligible pending tasks are currently available for claiming.".to_string()),
                        };
                        println!("{}", serde_json::to_string_pretty(&resp)?);
                    } else {
                        println!("✗ No eligible tasks available to claim (tasks are either completed, claimed, or waiting for prerequisites).");
                    }
                }
            }
        }

        TaskAction::Progress {
            task,
            message,
            agent,
            generation,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let agent_id = resolve_agent_id(agent.as_deref());
            let task_id = resolve_task_id(task.as_deref())
                .context("Task ID is required. Pass --task <id> or set STRATA_TASK_ID.")?;

            let ok = coordinator.update_task_progress_with_generation(&task_id, &agent_id, &message, generation)?;
            if !ok {
                bail!("Could not update progress: task '{}' not found, not active, assigned to another agent, or invalid claim generation.", task_id);
            }

            if json_mode {
                println!("{}", serde_json::json!({ "status": "ok", "task_id": task_id, "agent": agent_id }));
            } else {
                println!("✓ Task '{}' progress updated: '{}'", task_id, message);
            }
        }

        TaskAction::Complete {
            task,
            summary,
            artifact,
            artifact_content,
            agent,
            generation,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let agent_id = resolve_agent_id(agent.as_deref());
            let task_id = resolve_task_id(task.as_deref())
                .context("Task ID is required. Pass --task <id> or set STRATA_TASK_ID.")?;

            let art_payload = if let Some(path) = artifact {
                let content = std::fs::read_to_string(&path)
                    .with_context(|| format!("Failed to read artifact file at {:?}", path))?;
                Some(("file", content))
            } else {
                artifact_content.map(|content| ("text", content))
            };

            let task_artifact = art_payload.map(|(kind, payload)| {
                TaskArtifact::new(
                    format!("art-{}", &Uuid::new_v4().simple().to_string()[..12]),
                    &task_id,
                    &agent_id,
                    kind,
                    payload,
                )
            });

            let completed = coordinator.complete_task_with_generation(
                &task_id,
                &agent_id,
                summary.as_deref(),
                task_artifact.as_ref(),
                generation,
            )?;

            if !completed {
                bail!("Could not complete task: task '{}' was not found, not active, assigned to another agent, or invalid claim generation.", task_id);
            }

            // Broadcast IPC notification for task completion and lock release
            let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
            let (endpoint, _) = endpoint_for_workspace(&cwd);
            if let Ok(ipc) = IpcClient::connect(&endpoint).await {
                let _ = ipc
                    .publish(IpcEvent::TaskStateChanged {
                        task_id: task_id.clone(),
                        plan_id: None,
                        old_status: TaskStatus::Claimed,
                        new_status: TaskStatus::Completed,
                        agent_id: Some(agent_id.clone()),
                        timestamp_us: chrono::Utc::now().timestamp_micros(),
                    })
                    .await;
            }

            if json_mode {
                println!("{}", serde_json::json!({
                    "status": "completed",
                    "task_id": task_id,
                    "agent": agent_id,
                    "artifact_recorded": task_artifact.is_some()
                }));
            } else {
                println!("✓ Task '{}' completed by '{}'. Resource leases released and downstream tasks unblocked.", task_id, agent_id);
            }
        }

        TaskAction::Fail {
            task,
            error,
            agent,
            generation,
            json,
        } => {
            let json_mode = is_json_mode(json);
            let agent_id = resolve_agent_id(agent.as_deref());
            let task_id = resolve_task_id(task.as_deref())
                .context("Task ID is required. Pass --task <id> or set STRATA_TASK_ID.")?;

            let failed = coordinator.fail_task_with_generation(&task_id, &agent_id, &error, generation)?;
            if !failed {
                bail!("Could not mark task as failed: task '{}' was not found, not active, assigned to another agent, or invalid claim generation.", task_id);
            }

            // Broadcast IPC notification
            let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
            let (endpoint, _) = endpoint_for_workspace(&cwd);
            if let Ok(ipc) = IpcClient::connect(&endpoint).await {
                let _ = ipc
                    .publish(IpcEvent::TaskStateChanged {
                        task_id: task_id.clone(),
                        plan_id: None,
                        old_status: TaskStatus::Claimed,
                        new_status: TaskStatus::Failed,
                        agent_id: Some(agent_id.clone()),
                        timestamp_us: chrono::Utc::now().timestamp_micros(),
                    })
                    .await;
            }

            if json_mode {
                println!("{}", serde_json::json!({
                    "status": "failed",
                    "task_id": task_id,
                    "agent": agent_id,
                    "error": error
                }));
            } else {
                println!("✗ Task '{}' marked as failed by '{}'. Locks released.", task_id, agent_id);
            }
        }

        TaskAction::Inspect { task, json } => {
            let json_mode = is_json_mode(json);
            let task_record = coordinator
                .get_task(&task)?
                .ok_or_else(|| anyhow::anyhow!("Task '{}' not found on blackboard.", task))?;
            let artifacts = coordinator.get_task_artifacts(&task)?;

            if json_mode {
                println!("{}", serde_json::to_string_pretty(&serde_json::json!({
                    "task": task_record,
                    "artifacts": artifacts
                }))?);
            } else {
                println!("\n🔍 [Task Inspection: {}]", task_record.task_id);
                println!("═════════════════════════════════════════════════════════════");
                println!("Title:       {}", task_record.title);
                println!("Status:      {}", task_record.status);
                println!("Plan ID:     {}", task_record.plan_id.as_deref().unwrap_or("-"));
                println!("Agent:       {}", task_record.assigned_agent.as_deref().unwrap_or("unassigned"));
                println!("Prereqs:     {}", if task_record.dependencies.is_empty() { "-".to_string() } else { task_record.dependencies.join(", ") });
                println!("Resources:   {}", if task_record.required_resources.is_empty() { "-".to_string() } else { task_record.required_resources.join(", ") });
                if let Some(outputs) = &task_record.outputs {
                    println!("Outputs:     {}", outputs);
                }
                println!("\nAttached Artifacts: {}", artifacts.len());
                for a in &artifacts {
                    println!("  • [{}] {} (by {})", a.kind, a.payload, a.agent_id);
                }
                println!();
            }
        }

        TaskAction::Reclaim { stale_after, json } => {
            let json_mode = is_json_mode(json);
            let reclaimed = coordinator.reclaim_stale_tasks(stale_after)?;

            let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
            let (endpoint, _) = endpoint_for_workspace(&cwd);
            if let Ok(ipc) = IpcClient::connect(&endpoint).await {
                for id in &reclaimed {
                    let _ = ipc
                        .publish(IpcEvent::TaskStateChanged {
                            task_id: id.clone(),
                            plan_id: None,
                            old_status: TaskStatus::Running,
                            new_status: TaskStatus::Pending,
                            agent_id: None,
                            timestamp_us: chrono::Utc::now().timestamp_micros(),
                        })
                        .await;
                }
            }

            if json_mode {
                println!("{}", serde_json::json!({ "reclaimed": reclaimed }));
            } else if reclaimed.is_empty() {
                println!("✓ No orphaned tasks (none silent for more than {stale_after}s).");
            } else {
                println!("♻ Reclaimed {} orphaned task(s): {}", reclaimed.len(), reclaimed.join(", "));
            }
        }

        TaskAction::Worker(args) => {
            crate::commands::worker::run_worker(args, coordinator).await?;
        }
    }

    Ok(())
}
